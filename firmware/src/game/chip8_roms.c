static const chip8_cart_t k_carts[] = {
    {"demo", "CHIP-8 Demo", k_demo, (uint32_t)sizeof(k_demo)},
    {"snek", "Snek", k_snek, (uint32_t)sizeof(k_snek)},
    {"superpong", "Super Pong", k_superpong, (uint32_t)sizeof(k_superpong)},
    {"br8kout", "Br8kout", k_br8kout, (uint32_t)sizeof(k_br8kout)},
};

unsigned chip8_cart_count(void)
{
    return (unsigned)(sizeof(k_carts) / sizeof(k_carts[0]));
}

const chip8_cart_t *chip8_cart_at(unsigned index)
{
    if (index >= chip8_cart_count()) {
        return NULL;
    }
    return &k_carts[index];
}

const chip8_cart_t *chip8_cart_by_id(const char *id)
{
    unsigned i;

    if (id == NULL || id[0] == '\0') {
        return &k_carts[0];
    }
    for (i = 0u; i < chip8_cart_count(); i++) {
        if (strcmp(k_carts[i].id, id) == 0) {
            return &k_carts[i];
        }
    }
    return NULL;
}

const uint8_t *chip8_demo_rom(uint32_t *n)
{
    if (n != NULL) {
        *n = (uint32_t)sizeof(k_demo);
    }
    return k_demo;
}
